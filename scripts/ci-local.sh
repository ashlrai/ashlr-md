#!/usr/bin/env bash
# ci-local: run what the merge queue will run for your change, before pushing.
# Usage: scripts/ci-local.sh [base-ref]   (default origin/main)
# Scope comes from scripts/ci/select.mjs — the same selector the CI `select`
# job uses — so local and CI classification can never drift. JS gates and Rust
# checks run in parallel; target < 2 min on a warm machine.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
base="${1:-origin/main}"
files="$( { git diff --name-only "$base"...HEAD; git diff --name-only; git diff --name-only --cached; } | sort -u)"
sel="$(printf '%s\n' "$files" | node scripts/ci/select.mjs --event pull_request --files-file -)"
js="$(printf '%s\n' "$sel" | sed -n 's/^js=//p')"
rust="$(printf '%s\n' "$sel" | sed -n 's/^rust=//p')"
rust_args="$(printf '%s\n' "$sel" | sed -n 's/^rust_args=//p')"
[ -n "$rust_args" ] || rust_args=--workspace
msg="ci-local: js=$js rust=$rust"; [ "$rust" = true ] && msg="$msg cargo='$rust_args'"
echo "$msg (vs $base)"
pids=()
( bun run typecheck && bunx biome check src && bun run check:crypto && bun run check:doc-links \
  && bun run test:conflicts && bun run test:select \
  && if [ "$js" = true ]; then bunx vitest run --changed "$base" --passWithNoTests; fi ) & pids+=($!)
if [ "$rust" = true ]; then
  # rust_args is generated by select.mjs from a fixed crate allowlist; the word
  # splitting into separate -p flags is intentional.
  ( nice -n 10 cargo clippy $rust_args --manifest-path src-tauri/Cargo.toml --all-targets -- -D warnings \
    && nice -n 10 cargo test $rust_args --manifest-path src-tauri/Cargo.toml -- --test-threads=2 ) & pids+=($!)
fi
rc=0; for p in "${pids[@]}"; do wait "$p" || rc=1; done
[ $rc -eq 0 ] && echo "ci-local: PASS" || echo "ci-local: FAIL"
exit $rc
