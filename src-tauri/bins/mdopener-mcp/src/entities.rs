/// The `i`th name and its text.
fn entry(i: usize) -> (&'static str, &'static str) {
    let (name_start, text_start) = match i {
        0 => (0, 0),
        _ => ENDS[i - 1],
    };
    let (name_end, text_end) = ENDS[i];
    (
        &NAMES[name_start as usize..name_end as usize],
        &TEXTS[text_start as usize..text_end as usize],
    )
}

/// The text of the named reference `name` (`amp` is `&`), by case.
pub(crate) fn lookup(name: &str) -> Option<&'static str> {
    let (mut lo, mut hi) = (0, ENDS.len());
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (n, text) = entry(mid);
        match n.as_bytes().cmp(name.as_bytes()) {
            std::cmp::Ordering::Less => lo = mid + 1,
            std::cmp::Ordering::Greater => hi = mid,
            std::cmp::Ordering::Equal => return Some(text),
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::{entry, lookup, ENDS};

    /// [`lookup`] binary-searches, so the names must stay sorted, each once.
    #[test]
    fn names_are_sorted_and_unique() {
        assert_eq!(ENDS.len(), 2125);
        assert!((1..ENDS.len()).all(|i| entry(i - 1).0.as_bytes() < entry(i).0.as_bytes()));
        assert_eq!(entry(0), ("AElig", "\u{c6}"));
        assert_eq!(lookup("amp"), Some("&"));
        assert_eq!(lookup("zwnj"), Some("\u{200c}"));
        assert_eq!(lookup("nosuch"), None);
        assert_eq!(lookup(""), None);
    }
}
